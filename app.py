def load_test_results(filename, actual_col, predicted_col):
    results = pd.read_csv(BASE_DIR / filename)
    if not {actual_col, predicted_col}.issubset(results.columns):
        raise ValueError(f"{filename} is missing expected prediction columns.")
    # The scripts use chronological train/test splits, so test targets are the final rows.
    if len(results) > len(df):
        raise ValueError(f"{filename} contains more test rows than historical records.")
    results["Time"] = df["Time"].tail(len(results)).to_numpy()
    return results


with load_tab:
    st.subheader("Electricity Load Analysis")
    try:
        results = load_test_results("load_predictions.csv", "Actual Load (MW)", "Predicted Load (MW)")
        st.success("Saved electricity-load LSTM predictions loaded.")
        fig = go.Figure()
        fig.add_trace(go.Scatter(x=results["Time"], y=results["Actual Load (MW)"], mode="lines", name="Actual Load"))
        fig.add_trace(go.Scatter(x=results["Time"], y=results["Predicted Load (MW)"], mode="lines", name="LSTM Predicted Load"))
        fig.update_layout(title="Actual vs Predicted Electricity Load (Test Set)", xaxis_title="Time",
                          yaxis_title="Electricity Load (MW)", template="plotly_dark", height=450)
        st.plotly_chart(fig, use_container_width=True)
        actual, pred = results["Actual Load (MW)"], results["Predicted Load (MW)"]
        c1, c2 = st.columns(2)
        c1.metric("Test MAE", f"{np.mean(np.abs(actual - pred)):.3f} MW")
        c2.metric("Test RMSE", f"{np.sqrt(np.mean((actual - pred) ** 2)):.3f} MW")
        st.warning("Evaluation uses synthetic data, not real-world measurements.")
    except Exception as error:
        st.error(f"Unable to load load predictions: {error}")

