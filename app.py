        fig.update_layout(title="Actual vs Predicted Net Load (Timestamp-Aligned Test Set)", xaxis_title="Time",
                          yaxis_title="Net Load (MW)", template="plotly_dark", height=450)
        st.plotly_chart(fig, use_container_width=True)
        actual, pred = results["Actual Net Load (MW)"], results["Predicted Net Load (MW)"]
        c1, c2 = st.columns(2)
        c1.metric("Net-Load MAE", f"{np.mean(np.abs(actual - pred)):.3f} MW")
        c2.metric("Net-Load RMSE", f"{np.sqrt(np.mean((actual - pred) ** 2)):.3f} MW")
