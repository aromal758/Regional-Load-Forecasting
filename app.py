def load_demo_data():
    load_path = BASE_DIR / "demo_load_data.csv"
    solar_path = BASE_DIR / "demo_solar_data.csv"
    missing = [p.name for p in (load_path, solar_path) if not p.exists()]
    if missing:
        raise FileNotFoundError(
            f"Missing {', '.join(missing)}. Run load_model.py and solar_model.py first."
        )

    load = pd.read_csv(load_path)
    solar = pd.read_csv(solar_path)
    if not {"Time", "Electricity Load (MW)"}.issubset(load.columns):
        raise ValueError("demo_load_data.csv needs Time and Electricity Load (MW) columns.")
    if not {"Time", "Solar Generation (MW)"}.issubset(solar.columns):
        raise ValueError("demo_solar_data.csv needs Time and Solar Generation (MW) columns.")

    load["Time"] = pd.to_datetime(load["Time"], errors="coerce")
    solar["Time"] = pd.to_datetime(solar["Time"], errors="coerce")
    load["Electricity Load (MW)"] = pd.to_numeric(load["Electricity Load (MW)"], errors="coerce")
    solar["Solar Generation (MW)"] = pd.to_numeric(solar["Solar Generation (MW)"], errors="coerce")
    load = load.dropna(subset=["Time", "Electricity Load (MW)"])
    solar = solar.dropna(subset=["Time", "Solar Generation (MW)"])

    # Match historical load and solar values by timestamp.
    df = pd.merge(
        load[["Time", "Electricity Load (MW)"]],
        solar[["Time", "Solar Generation (MW)"]],
        on="Time", how="inner", validate="one_to_one"
    )
    if df.empty:
        raise ValueError("The load and solar files have no matching timestamps.")
    if (df[["Electricity Load (MW)", "Solar Generation (MW)"]] < 0).any().any():
        raise ValueError("Power values cannot be negative.")
    return df.sort_values("Time").reset_index(drop=True)


def validate_upload(file):
    df = pd.read_csv(file)
    required = ["Time", "Electricity Load (MW)", "Solar Generation (MW)"]
    if not all(c in df.columns for c in required):
        raise ValueError("CSV needs columns: Time, Electricity Load (MW), Solar Generation (MW).")
    df["Time"] = pd.to_datetime(df["Time"], errors="coerce")
    for c in required[1:]:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    df = df.dropna(subset=required)
    if df.empty:
        raise ValueError("No valid data rows found in the uploaded CSV.")
    if (df[required[1:]] < 0).any().any():
        raise ValueError("Power values cannot be negative.")
    return df[required].sort_values("Time").drop_duplicates("Time").reset_index(drop=True)


def make_chart(data, columns, title):
    fig = go.Figure()
    for column in columns:
        fig.add_trace(go.Scatter(x=data["Time"], y=data[column], name=column, mode="lines"))
    fig.update_layout(
        title=title, template="plotly_dark", height=420,
        hovermode="x unified", xaxis_title="Time", yaxis_title="Power (MW)"
    )
    return fig


